import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseRecipe } from '../../web/scripts/build-data.mjs'

const root = fileURLToPath(new URL('../../', import.meta.url))
const ids = [
  'soup/昂刺鱼豆腐汤/昂刺鱼豆腐汤', 'soup/白萝卜丝清汤',
  'meat_dish/奥尔良风味烤鸡腿/奥尔良风味烤鸡腿', 'meat_dish/澳门湿版免治牛肉饭/澳门湿版免治牛肉饭',
  'dessert/奥利奥冰淇淋/奥利奥冰淇淋', 'dessert/草莓冰淇淋/草莓冰淇淋',
  'vegetable_dish/拔丝土豆/拔丝土豆', 'vegetable_dish/白灼菜心/白灼菜心',
  'drink/耙耙柑茶/耙耙柑茶', 'drink/百香果橙子特调/百香果橙子特调',
  'aquatic/白灼虾/白灼虾', 'aquatic/鳊鱼炖豆腐/鳊鱼炖豆腐',
  'semi-finished/半成品意面', 'semi-finished/空气炸锅鸡翅中/空气炸锅鸡翅中',
  'condiment/草莓酱/草莓酱', 'condiment/葱油',
  'breakfast/茶叶蛋', 'breakfast/蛋煎糍粑',
  'staple/炒方便面/炒方便面', 'staple/炒河粉',
]
const plain = text => text.replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*_`]/g, '').trim()
const recipes = ids.map(id => {
  const recipe = parseRecipe(path.join(root, 'dishes', `${id}.md`))
  if (recipe.id !== id || !recipe.steps.length) throw new Error(`Invalid sample: ${id}`)
  return {
    ...recipe, description: plain(recipe.description), images: [], cover: null,
    tips: recipe.tips.map(plain).filter(Boolean),
    steps: recipe.steps.map(step => ({ ...step, text: plain(step.text), notes: step.notes.map(plain).filter(Boolean) })),
  }
})
const output = path.join(root, 'miniprogram/src/data/samples.ts')
fs.writeFileSync(output, `// Generated by scripts/build-samples.mjs.\nimport type { Recipe } from '../../../packages/recipe-core/types'\nexport const samples: Recipe[] = ${JSON.stringify(recipes, null, 2)}\n`)
console.log(`Generated ${recipes.length} recipes; ${fs.statSync(output).size} bytes; no images copied.`)
