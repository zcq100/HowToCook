import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseRecipe } from '../../web/scripts/build-data.mjs'

const root = fileURLToPath(new URL('../../', import.meta.url))
const dishes = path.join(root, 'dishes')
function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) return entry.name === 'template' ? [] : walk(file)
    return entry.name.endsWith('.md') && entry.name !== 'index.md' ? [file] : []
  })
}
const plain = text => text.replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*_`]/g, '').trim()
const recipes = walk(dishes).map(file => {
  const recipe = parseRecipe(file)
  if (!recipe.id || !recipe.name || !recipe.steps.length) throw new Error(`Invalid recipe: ${file}`)
  return {
    ...recipe, description: plain(recipe.description), servingsNote: plain(recipe.servingsNote), images: [], cover: null,
    ingredients: recipe.ingredients.map(item => ({ ...item, name: plain(item.name), amounts: item.amounts.map(plain).filter(Boolean) })),
    tips: recipe.tips.map(plain).filter(Boolean),
    steps: recipe.steps.map(step => ({ ...step, text: plain(step.text), notes: step.notes.map(plain).filter(Boolean) })),
  }
}).sort((a, b) => a.name.localeCompare(b.name, 'zh') || a.id.localeCompare(b.id))
if (new Set(recipes.map(recipe => recipe.id)).size !== recipes.length) throw new Error('Duplicate recipe IDs')
const output = path.join(root, 'miniprogram/src/data/recipes.ts')
// Keep JSON inside a string so tsc does not expand the full dataset into an
// indented object literal. The runtime module still provides a typed array.
fs.writeFileSync(output, `// Generated by scripts/build-data.mjs; all recipes, no images.\nimport type { Recipe } from '../../../packages/recipe-core/types'\nexport const recipes: Recipe[] = JSON.parse(${JSON.stringify(JSON.stringify(recipes))})\n`)
fs.writeFileSync(path.join(root, 'miniprogram/src/data/manifest.json'), JSON.stringify({
  count: recipes.length, ids: recipes.map(recipe => recipe.id),
  categories: [...new Set(recipes.map(recipe => recipe.category))],
}, null, 2) + '\n')
console.log(`Generated all ${recipes.length} recipes; ${fs.statSync(output).size} bytes; no images copied or downloaded.`)
